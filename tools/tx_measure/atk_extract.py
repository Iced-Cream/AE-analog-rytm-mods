"""Extract the BD TX-9 click and the BD TX-8 attack pulse from the plugins (run in WSL,
needs txrun and the decoded blobs) and write tools/tx_atk_data.py, which
gen_tx_tables.py turns into tables.

TX-9: ATK adds a fixed waveform (render(ATK) - render(ATK 0) is the same shape at every
ATK, PTCH, DEC, TUNE, DPTH to 0 residual), scaled by a curve of ATK and by ACC.
TX-8: ATK cuts the first peak with a negative pulse 2..5 ms in (saturating by ATK 32),
then changes the body in a pitch-dependent way; only the pulse (PTCH 64, ATK 64,
first 5.5 ms, faded from 3.5 ms) is kept.

Usage: python3 atk_extract.py TXRUN BINDIR OUT.py"""
import math
import os
import struct
import subprocess
import sys

TXRUN, BINS, OUT = sys.argv[1:4]
FS_TX, FS = 44100.0, 48000.0
TMP = os.path.expanduser('~/atk_x.f32')


def render(blob, params, blocks=40):
    env = dict(os.environ, TXOUT=TMP)
    subprocess.run([TXRUN, f'{BINS}/{blob}.bin', str(blocks)] + [str(p) for p in params],
                   env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    d = open(TMP, 'rb').read()
    return struct.unpack('<%df' % (len(d) // 4), d)


def diff(blob, a, b):
    return [x - y for x, y in zip(render(blob, a), render(blob, b))]


def resample(x, ms, fade_from_ms):
    """44.1 -> 48 kHz (linear interpolation; the click has little above 10 kHz),
    cut at ms with a raised-cosine fade from fade_from_ms."""
    n = int(ms * FS / 1000)
    f0 = fade_from_ms * FS / 1000
    out = []
    for i in range(n):
        t = i * FS_TX / FS
        k = int(t)
        v = x[k] + (x[k + 1] - x[k]) * (t - k)
        if i > f0:
            v *= 0.5 + 0.5 * math.cos(math.pi * (i - f0) / (n - f0))
        out.append(v)
    return out


ATKS = (0, 8, 16, 24, 32, 48, 64, 80, 96, 112, 127)
ACCS = (0, 32, 64, 96, 127)

# TX-9 BD: PTCH DEC TUNE ATK ACC DPTH DRV
ref9 = diff('TX9-BD', (64, 64, 64, 127, 96, 64, 0), (64, 64, 64, 0, 96, 64, 0))
e9 = sum(v * v for v in ref9[:600])
def proj9(d):
    return sum(u * v for u, v in zip(d[:600], ref9[:600])) / e9
g9 = {a: (proj9(diff('TX9-BD', (64, 64, 64, a, 96, 64, 0), (64, 64, 64, 0, 96, 64, 0))) if a else 0.0)
      for a in ATKS}
acc9 = {c: proj9(diff('TX9-BD', (64, 64, 64, 127, c, 64, 0), (64, 64, 64, 0, c, 64, 0))) for c in ACCS}
click9 = resample(ref9, 10.5, 9.5)

# TX-8 BD: PTCH DEC TONE ACC SIGH ATK
ref8 = diff('TX8-BD', (64, 64, 64, 96, 64, 64), (64, 64, 64, 96, 64, 0))
pulse8 = resample(ref8, 5.5, 3.5)
def proj8(d):
    w = resample(d, 5.5, 3.5)
    return sum(u * v for u, v in zip(w, pulse8)) / sum(v * v for v in pulse8)
g8 = {a: (proj8(diff('TX8-BD', (64, 64, 64, 96, 64, a), (64, 64, 64, 96, 64, 0))) if a else 0.0)
      for a in ATKS}
acc8 = {c: proj8(diff('TX8-BD', (64, 64, 64, c, 64, 64), (64, 64, 64, c, 64, 0))) for c in ACCS}

with open(OUT, 'w') as f:
    f.write('"""Generated by tools/tx_measure/atk_extract.py from the TX plugins (emulator).\n'
            'Waveforms at 48 kHz in Machinedrum full-scale units, at ACC 96."""\n\n')
    f.write(f'CLICK9 = {[round(v, 6) for v in click9]}\n')
    f.write(f'CLICK9_ATK = {dict((k, round(v, 4)) for k, v in g9.items())}\n')
    f.write(f'CLICK9_ACC = {dict((k, round(v, 4)) for k, v in acc9.items())}\n')
    f.write(f'PULSE8 = {[round(v, 6) for v in pulse8]}\n')
    f.write(f'PULSE8_ATK = {dict((k, round(v, 4)) for k, v in g8.items())}\n')
    f.write(f'PULSE8_ACC = {dict((k, round(v, 4)) for k, v in acc8.items())}\n')
print('click9 peak %.4f, %d samples; pulse8 peak %.4f, %d samples' % (
    max(abs(v) for v in click9), len(click9), max(abs(v) for v in pulse8), len(pulse8)))
print('ATK9', g9); print('ACC9', acc9); print('ATK8', g8); print('ACC8', acc8)
